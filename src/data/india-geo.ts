/**
 * Filter all Indian States & UTs matching query
 */
export function getIndianStates(query: string = ''): string[] {
  const q = query.toLowerCase().trim();
  const allStates = INDIAN_STATES_AND_DISTRICTS.map((s) => s.state);
  if (!q) return allStates;
  return allStates.filter((s) => s.toLowerCase().includes(q));
}

/**
 * Filter Districts scoped to a State (or across all of India if no state provided)
 */
export function getDistricts(stateName?: string, query: string = ''): string[] {
  const q = query.toLowerCase().trim();
  
  if (stateName) {
    const matchedState = INDIAN_STATES_AND_DISTRICTS.find(
      (s) => s.state.toLowerCase() === stateName.toLowerCase().trim()
    );
    if (matchedState) {
      if (!q) return matchedState.districts;
      return matchedState.districts.filter((d) => d.toLowerCase().includes(q));
    }
  }

  // If no state provided or state not matched, search across all districts
  const all = Array.from(
    new Set(INDIAN_STATES_AND_DISTRICTS.flatMap((s) => s.districts))
  );
  if (!q) return all.slice(0, 30);
  return all.filter((d) => d.toLowerCase().includes(q)).slice(0, 30);
}

/**
 * Filter Major Cities/Towns scoped to a State or District
 */
export function getCities(stateName?: string, districtName?: string, query: string = ''): string[] {
  const q = query.toLowerCase().trim();

  if (stateName) {
    const matchedState = INDIAN_STATES_AND_DISTRICTS.find(
      (s) => s.state.toLowerCase() === stateName.toLowerCase().trim()
    );
    if (matchedState && matchedState.majorCities) {
      if (!q) return matchedState.majorCities;
      return matchedState.majorCities.filter((c) => c.toLowerCase().includes(q));
    }
  }

  const allCities = Array.from(
    new Set(INDIAN_STATES_AND_DISTRICTS.flatMap((s) => s.majorCities || []))
  );
  if (!q) return allCities.slice(0, 30);
  return allCities.filter((c) => c.toLowerCase().includes(q)).slice(0, 30);
}

/**
 * Given a district name, find the matching state
 */
export function findStateByDistrict(districtName: string): string | null {
  const dClean = districtName.toLowerCase().trim();
  for (const s of INDIAN_STATES_AND_DISTRICTS) {
    if (s.districts.some((d) => d.toLowerCase() === dClean)) {
      return s.state;
    }
  }
  return null;
}
